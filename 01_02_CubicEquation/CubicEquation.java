public class CubicEquation {

	public static void main(String[] args) {
		int x = 3;
		int f = x * x * x + 2 * x * x + 4 * x + 5;
		System.out.println("f(" + x + ") = " + f);

        x = 5;
		f = x * x * x + 2 * x * x + 4 * x + 5;
		System.out.println("f(" + x + ") = " + f);	
		
		x = 10;
		f = x * x * x + 2 * x * x + 4 * x + 5;
		System.out.println("f(" + x + ") = " + f);	

	}
}
